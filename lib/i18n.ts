export async function getLocale(): Promise<Locale> {
  const store = await cookies();
  return store.get("signalcore_locale")?.value === "tr" ? "tr" : "en";
}

export function navCopy(locale: Locale) {
  return nav[locale];
}

export function dashboardCopy(locale: Locale) {
  return dashboard[locale];
}
